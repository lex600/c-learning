#include <stdio.h>

/* ---- 示例：判断一个数是不是素数 ---- */
/* 函数的三要素：返回类型 int、函数名 isPrime、参数列表 (int n) */
int isPrime(int n)
{
    int i;

    if (n < 2) {
        return 0;               /* 0 和 1 都不是素数 */
    }

    /* 只需要试到 sqrt(n)，但这里先用最朴素的写法，方便理解 */
    for (i = 2; i < n; i++) {
        if (n % i == 0) {
            return 0;           /* 找到一个因子，立刻返回，不用再算 */
        }
    }

    return 1;                   /* 循环跑完都没找到因子，是素数 */
}

int main(void)
{
    int n;

    printf("请输入一个整数：");
    scanf("%d", &n);

    if (isPrime(n)) {
        printf("%d 是素数\n", n);
    } else {
        printf("%d 不是素数\n", n);
    }

    return 0;
}

